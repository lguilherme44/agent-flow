/**
 * Every string the Deck writes, in English — and the **type** the other language obeys.
 *
 * `Dictionary` is `typeof en`, and `pt-BR.ts` is annotated with it. A key that is missing,
 * renamed or extra there is a compile error, which is the only guard strong enough for a
 * surface this size: a parity test that runs after the fact still lets a half-translated
 * screen reach a person, and half-translated is what nobody notices until it ships.
 *
 * **Functions where a value goes in.** A count is an argument rather than a `{n}`
 * placeholder, because the two languages do not agree about what a count changes:
 * `1 task` → `2 tasks` is a suffix, and `1 tarefa` → `2 tarefas` agrees with a noun that a
 * template cannot see. Each dictionary writes its own sentence and the compiler checks the
 * arguments.
 *
 * **What is deliberately not here.** Prose the *server* sends — the attention queue's
 * `what` and `why`, a board card's reason, a delivery's `detail`, the doctor's
 * remediations, every refusal message — is written in `src/core` and `src/app` and printed
 * verbatim by the CLI too. This bundle renders those; it does not author them, so it
 * cannot translate them.
 */

