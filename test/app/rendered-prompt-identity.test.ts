/**
 * NFR-002 — with no operator amendment, the implementation and final-review prompts are
 * the ones `master` sent.
 *
 * **Why fixtures, and why captured first.** The amendments work delivers its text through
 * two existing variables, `failureContext` and `sdd`, so that an empty amendment list
 * changes nothing without touching a template. "Changes nothing" is only provable against
 * what the unchanged tree rendered. A comparison against a render of the edited code proves
 * the code agrees with itself, which it always does. So both fixtures were written once,
 * from the tree before any source change, and this file only reads them: there is no update
 * flag and no environment switch, because a fixture that can be regenerated by the change it
 * guards is a fixture that guards nothing.
 *
 * **Real templates, real renderers.** The implementation prompt goes through the real
 * `TaskExecutor` and `StageRunner` exactly as a sequential run sends it; the final-review
 * prompt goes through `review()` and is read off the stdin of the spawned CLI, which is where
 * the Claude adapter puts it. A stub template would make both comparisons trivially true.
 *
 * **The planning and plan-review prompts, the same way.** The executor-commands work appends
 * one placeholder to each of the five planning and plan-review templates, and promises that
 * for a project with no declared command and no runner grant it renders as nothing. Their five
 * fixtures were captured from the templates before any of them was edited, through the real
 * `PlanningPipeline`, and are read here under the same rule: no update flag.
 */

const REAL_PROMPTS = join(import.meta.dirname, '../../prompts');
const FIXTURES = join(import.meta.dirname, '../fixtures/rendered-prompts');

/**
 * The only normalisation, and why it is needed.
 *
 * With `core.autocrlf=true` and no `.gitattributes`, a Windows checkout holds the templates
 * with CRLF, and `prompt-loader` passes the body's `\r\n` through untouched. A Linux checkout
 * holds LF. A byte comparison would then pass on one host and fail on the other for a reason
 * that says nothing about the product. The fixtures are stored LF-only, as JSON strings so
 * that `autocrlf` cannot rewrite them either.
 *
 * Nothing else is normalised: every other input below is fixed by the fakes (`FixedClock`,
 * an in-memory filesystem, a scripted process runner), so no path or duration varies.
 */
function lf(text: string): string {
  return text.replace(/\r\n/g, '\n');
}

function fixture(name: string): string {
  const parsed: unknown = JSON.parse(readFileSync(join(FIXTURES, name), 'utf8'));
  if (typeof parsed !== 'string') throw new Error(`${name} does not hold a JSON string`);
  return parsed;
}

function seedRealPrompts(fs: InMemoryFileSystem, dir: string): void {
  for (const file of readdirSync(REAL_PROMPTS)) {
    if (file.endsWith('.md')) fs.seed(`${dir}/${file}`, readFileSync(join(REAL_PROMPTS, file), 'utf8'));
  }
}

