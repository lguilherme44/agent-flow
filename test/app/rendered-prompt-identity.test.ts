async function renderFinalReview(
  sdd: string,
  /** Seeded on the run before `review()`; the time is the fixed clock's. */
  amendments: readonly Omit<Amendment, 'at'>[] = [],
): Promise<string> {
  const fs = new InMemoryFileSystem();
  const clock = new FixedClock();

  fs.seed('/repo/.agent-flow/config.yaml', PROJECT_CONFIG);
  seedRealPrompts(fs, '/install/prompts');

  const store = new StateStore({ fs, clock, projectDir: '/repo' });
  const run = await store.createRun('csv export', () => ({
    isolationMode: 'none' as const,
    workflow: 'standard' as const,
  }));

  await store.writeArtifact(run.runId, 'request', 'Add a CSV export to the report page.\n');
  await store.writeArtifact(run.runId, 'sdd', sdd);
  await store.writeArtifact(run.runId, 'plan', JSON.stringify(PLAN, null, 2));
  await store.updateRun(run.runId, (state) => ({
    ...state,
    status: 'approved',
    approved: true,
    approvedAt: clock.now(),
    approvedPlanHash: planHash(PLAN),
    tasks: [{ id: 'TASK-001', state: 'running', attempts: 1, infrastructureFailures: 0 }],
  }));
  await store.updateRun(run.runId, (state) => ({
    ...state,
    stage: 'implementation',
    tasks: [{ id: 'TASK-001', state: 'completed', attempts: 1, infrastructureFailures: 0 }],
  }));
  if (amendments.length > 0) {
    await store.updateRun(run.runId, (state) => ({
      ...state,
      amendments: amendments.map((amendment) => ({ ...amendment, at: clock.now() })),
    }));
  }

  // The runner that records what it was handed. Git and the validation shell get fixed
  // answers, so `diffStat`, `changedFiles` and `commandResults` are the same on every host.
  const received: string[] = [];
  const processRunner = new FakeProcessRunner().always((opts: ProcessSpawnOptions) => {
    if (opts.command === 'git') {
      // `diffStat()` and `changedFiles()` as a sequential review asks them. The `-z` form of
      // status belongs to the read-only twin, which is left seeing a clean tree.
      if (opts.args.includes('--stat')) {
        return { exitCode: 0, stdout: ' src/export.ts | 12 ++++++++++++\n' };
      }
      if (opts.args.includes('--porcelain=v1') && !opts.args.includes('-z')) {
        return { exitCode: 0, stdout: ' M src/export.ts\n' };
      }
      return { exitCode: 0, stdout: '' };
    }
    if (opts.args.includes('--version')) return { exitCode: 0, stdout: '1.0.0' };
    const stdin = opts.stdin ?? '';
    if (stdin.includes('ROLE: FINAL_REVIEW_AGENT')) received.push(stdin);
    if (opts.args.includes('--json-schema')) {
      return {
        exitCode: 0,
        stdout: JSON.stringify({
          is_error: false,
          subtype: 'success',
          result: JSON.stringify(PASS),
          structured_output: PASS,
        }),
      };
    }
    return { exitCode: 0, stdout: '' };
  });

  const deps = fakeRunActionDeps({
    fs,
    clock,
    processRunner,
    projectDir: '/repo',
    globalConfigPath: '/install/config.yaml',
    promptsDir: '/install/prompts',
    host: new FakeHost(),
    owner: 'cli',
  });

  const outcome = await review(deps, run.runId);
  if (!outcome.ok) throw new Error(`review refused: ${outcome.error.code}`);
  if (received.length !== 1) {
    throw new Error(`expected one final-review prompt, got ${String(received.length)}`);
  }
  return lf(received[0] ?? '');
}

