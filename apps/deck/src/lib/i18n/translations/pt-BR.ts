/**
 * O Deck em português, e é este o idioma em que ele abre.
 *
 * Anotado com `Dictionary`, então uma chave que falte, sobre ou mude de nome é **erro de
 * compilação** — não uma tela meio traduzida que só aparece para quem estiver olhando.
 *
 * Duas regras que valem para o arquivo inteiro:
 *
 *   - **`words` é vocabulário solto.** Esses valores caem em chips, células e crachás, sem
 *     substantivo do lado. Uma forma que precise concordar com um substantivo estaria
 *     errada metade das vezes, então a escolha é sempre neutra ou masculina — e onde o
 *     mesmo token serve a dois gêneros (`open` de um achado e de uma conversa), a redação
 *     funciona nos dois (`em aberto`).
 *   - **Frases com substantivo do lado não passam por `words`.** Elas são escritas
 *     inteiras aqui, para que `TASK-004 concluída` concorde.
 *
 * Identificadores nunca são traduzidos: `TASK-004`, `AF-2026-001`, nomes de branch, de
 * runner e de arquivo são o que o servidor emitiu e o que o terminal aceita de volta.
 */
