/** A plan hash the run is approved under. Its value is arbitrary; only equality matters. */
const APPROVED_HASH = 'sha256:approved-plan';

async function renderImplementation(options: {
  failureContext: boolean;
  /** Approve the run under `APPROVED_HASH`, as every answered run is. */
  approved?: boolean;
  /** One `answer` amendment for TASK-001, recorded under `APPROVED_HASH`. */
  answer?: string;
}): Promise<string> {
  const fs = new InMemoryFileSystem();
  const clock = new FixedClock();
  const runner = new FakeAgentRunner('claude', CAPS);
  const prompts = '/pkg/prompts';

  seedRealPrompts(fs, prompts);
  fs.seed(`${PROJECT}/AGENTS.md`, AGENTS_MD);

  const globalConfig = GlobalConfigSchema.parse(parseYaml(DEFAULT_GLOBAL_CONFIG_YAML));
  const store = new StateStore({ fs, clock, projectDir: PROJECT });
  const run = await store.createRun('csv export');

  const executor = new TaskExecutor({
    fs,
    clock,
    store,
    stageRunner: new StageRunner({
      fs,
      clock,
      store,
      config: globalConfig,
      capabilities: { claude: CAPS },
      promptLoader: new PromptLoader({ fs, promptsDir: prompts }),
      getRunner: () => runner,
      projectDir: PROJECT,
    }),
    processRunner: new FakeProcessRunner().always({ exitCode: 0 }),
    config: {
      global: globalConfig,
      project: ProjectConfigSchema.parse({
        project: { name: 'demo', type: 'node' },
        commands: { test: 'npm test' },
      }),
    },
    projectDir: PROJECT,
  });

  runner.pushText(REPORT);

  if (options.approved === true || options.answer !== undefined) {
    const { answer } = options;
    await store.updateRun(run.runId, (state) => ({
      ...state,
      approved: true,
      approvedAt: clock.now(),
      approvedPlanHash: APPROVED_HASH,
      ...(answer === undefined
        ? {}
        : {
            amendments: [
              {
                id: 'AMD-001',
                kind: 'answer' as const,
                actor: { kind: 'keyboard' as const },
                at: clock.now(),
                text: answer,
                task: 'TASK-001',
                planHash: APPROVED_HASH,
              },
            ],
          }),
    }));
  }

  if (options.failureContext) {
    // The only way a failure context reaches this slot: a second attempt with the packet
    // on disk. Sequential mode passes no workspace and so always renders attempt 1.
    fs.seed(runPaths(PROJECT, run.runId).attemptContext('TASK-001', 2), JSON.stringify(PACKET));
    await store.updateRun(run.runId, (state) => ({
      ...state,
      tasks: [{ id: 'TASK-001', state: 'ready' as const, attempts: 1, infrastructureFailures: 0 }],
    }));
    await executor.execute(TASK, run.runId, IMPLEMENTATION_SDD, { path: PROJECT, attempt: 2 });
  } else {
    await store.updateRun(run.runId, (state) => ({
      ...state,
      tasks: [{ id: 'TASK-001', state: 'ready' as const, attempts: 0, infrastructureFailures: 0 }],
    }));
    // No workspace: what the scheduler passes in sequential mode (`prepareWorkspace` returns
    // none when no workspaces are wired), so the attempt is 1 and the failure context empty.
    await executor.execute(TASK, run.runId, IMPLEMENTATION_SDD);
  }

  const prompt = runner.calls.at(-1)?.prompt;
  if (prompt === undefined) throw new Error('the implementation stage never reached the runner');
  return lf(prompt);
}

